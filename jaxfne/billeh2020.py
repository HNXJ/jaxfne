def _pair(pre: str, post: str) -> tuple[str, str]:
    key = (str(pre), str(post))
    if key not in A_LITERATURE:
        raise ValueError(f"unknown Billeh 2020 population pair {key!r}; populations are {POPULATIONS}")
    return key


def peak_probability(pre: str, post: str) -> float:
    """A_new: the probability at r = 0 before the cap at 1."""
    key = _pair(pre, post)
    s = SIGMA_UM[key]
    return A_LITERATURE[key] / ((s / R0_UM) ** 2 * (1.0 - np.exp(-((R0_UM / s) ** 2))))


def connection_probability(pre: str, post: str, r_um) -> np.ndarray:
    """p(r) = min(1, A_new exp(-r^2 / sigma^2)) at lateral distances ``r_um`` (um, finite, >= 0).

    Billeh et al. 2020, doi:10.1016/j.neuron.2020.01.040.
    """
    key = _pair(pre, post)
    r = np.asarray(r_um, np.float64)
    if not np.all(np.isfinite(r)) or np.any(r < 0):
        raise ValueError("r_um must be finite and non-negative")
    return np.minimum(1.0, peak_probability(*key) * np.exp(-(r ** 2) / SIGMA_UM[key] ** 2))
