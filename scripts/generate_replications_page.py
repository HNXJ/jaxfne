#!/usr/bin/env python3
"""Generate docs/replications.md from dashboard/sources.json.

One row per paper on the replication dashboard, linking its page there, plus the roadmap.

Usage:
    python scripts/generate_replications_page.py --write
    python scripts/generate_replications_page.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "dashboard" / "sources.json"
OUT = ROOT / "docs" / "replications.md"
DASHBOARD = "https://hnxj.github.io/jaxfne/dashboard/"


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(sources: dict) -> str:
    lines = [
        "# Replications",
        "",
        "Published models rerun with jaxfne. Each paper has a page on the",
        f"[replication dashboard]({DASHBOARD}) with its question, preregistration, criteria,",
        "verdicts and figures. Stages P0–P7 run from selection to insight; a replication counts",
        "as done with jaxfne only when it runs through the library (P6).",
        "",
        f'<iframe class="jx-frame" src="{DASHBOARD}" loading="lazy" title="Replication dashboard"></iframe>',
        "",
        "| Paper | Class | Release | Stage | Verdict |",
        "|---|---|---|---|---|",
    ]
    for p in sources["papers"]:
        verdict = p.get("verdict") or "—"
        if p.get("verdict_note"):
            verdict = f"{verdict}: {p['verdict_note']}"
        title = f"[{cell(p['title'])}]({DASHBOARD}#model/{p['id']})"
        lines.append(
            f"| {title}<br>{cell(p['citation'])} | {cell(p['class'])} | {cell(p['release'])} "
            f"| {cell(p.get('stage') or '—')} | {cell(verdict)} |"
        )
    roadmap = sources.get("roadmap", [])
    if roadmap:
        lines += ["", "## Not started", "", "| Release | Model | Needs |", "|---|---|---|"]
        lines += [f"| {cell(r['release'])} | {cell(r['model'])} | {cell(r['needs'])} |" for r in roadmap]
    lines += ["", "Generated by `scripts/generate_replications_page.py` from `dashboard/sources.json`.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    text = render(json.loads(SOURCES.read_text(encoding="utf-8")))
    if args.write:
        OUT.write_bytes(text.encode("utf-8"))
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    current = OUT.read_bytes().decode("utf-8") if OUT.exists() else None
    if current != text:
        print(f"{OUT.relative_to(ROOT)} is stale: run --write", file=sys.stderr)
        return 1
    print("replications page current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
