#!/usr/bin/env python3
"""Generate docs/start/replications.md from dashboard/sources.json.

One row per paper on the replication dashboard, linking its page there, plus the roadmap and, when the
derived data holds one, the reference audit.

Usage:
    python scripts/generate_replications_page.py --write
    python scripts/generate_replications_page.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "dashboard" / "sources.json"
DERIVED = ROOT / "dashboard" / "data" / "replications.json"
OUT = ROOT / "docs" / "start" / "replications.md"
DASHBOARD = "https://hnxj.github.io/jaxfne/dashboard/"


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def verdict_cells(p: dict) -> list:
    """Paper, library-path and methods verdicts from the derived summary, falling back to the
    recorded verdict for rows that predate it. A missing verdict shows as an em dash."""
    summary = p.get("verdict_summary") or {}
    paper_v = summary.get("paper", p.get("verdict"))
    lib = summary.get("library") or {}
    library_v = f"{lib['stage']} {str(lib['verdict']).upper()}" if lib else None
    return [paper_v, library_v, summary.get("methods")]


AUDIT_KEY = ("H1 mechanism realized in the core, H2 reproduction evidence, H3 dashboard readiness; each is "
             "scored -1 to +1 by a three-model council. Action is the first rule of the OCMA glossary that the "
             "scores meet.")


def score(v) -> str:
    """Two decimals, halves rounded up in magnitude as JavaScript toFixed does; null as an en dash."""
    if v is None:
        return "–"
    return str(Decimal(v).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def audit_section(audit: dict) -> list:
    """The Reference audit section: the factor key, then one table row per audited reference."""
    lines = ["", "## Reference audit (OCMA)", "", AUDIT_KEY, "",
             "| Reference | Section | H1 | H2 | H3 | Action |", "|---|---|---|---|---|---|"]
    for r in audit["rows"]:
        lines.append(f"| {cell(r['reference'])} | {cell(r['section'])} | {score(r['H1'])} | {score(r['H2'])} "
                     f"| {score(r['H3'])} | {cell(r['action'])} |")
    return lines


def render(sources: dict, audit: dict | None = None) -> str:
    lines = [
        "# Replications",
        "",
        "Published models rerun with jaxfne. Each paper has a page on the",
        f"[replication dashboard]({DASHBOARD}) with its question, preregistration, criteria,",
        "verdicts and figures. Stages P0–P7 run from selection to insight; a replication counts",
        "as done with jaxfne only when it runs through the library (P6).",
        "",
        f"[Open the replication dashboard]({DASHBOARD})",
        "",
        "Replica is the share of the paper's result panels reproduced, out of 100 (pass 1, partial 0.5,",
        "fail or not run 0); 100 is a full replica. A dash means no panel inventory yet.",
        "",
        "| Paper | Class | Release | Stage | Replica | Paper | Library | Methods |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for p in sources["papers"]:
        verdict = p.get("verdict") or "—"
        if p.get("verdict_note"):
            verdict = f"{verdict}: {p['verdict_note']}"
        paper_v, library_v, methods_v = verdict_cells(p)
        if p.get("verdict_note"):
            paper_v = f"{paper_v or '—'}: {p['verdict_note']}"
        else:
            paper_v = paper_v or "—"
        title = f"[{cell(p['title'])}]({DASHBOARD}#model/{p['id']})"
        score = (p.get("replica") or {}).get("score")
        replica_v = "—" if score is None else f"{score}/100"
        lines.append(
            f"| {title}<br>{cell(p['citation'])} | {cell(p['class'])} | {cell(p['release'])} "
            f"| {cell(p.get('stage') or '—')} | {replica_v} | {cell(paper_v)} "
            f"| {cell(library_v or '—')} | {cell(methods_v or '—')} |"
        )
    roadmap = sources.get("roadmap", [])
    if roadmap:
        lines += ["", "## Not started", "", "| Release | Model | Needs |", "|---|---|---|"]
        lines += [f"| {cell(r['release'])} | {cell(r['model'])} | {cell(r['needs'])} |" for r in roadmap]
    if audit:
        lines += audit_section(audit)
    lines += ["", "Generated by `scripts/generate_replications_page.py` from `dashboard/sources.json`.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    # sources.json holds no derived verdicts; the library and methods columns come from the
    # derived data that `build_dashboard_data.py` writes, so the page shows what the dashboard shows.
    audit = None
    if DERIVED.exists():
        derived_doc = json.loads(DERIVED.read_text(encoding="utf-8"))
        derived = {p["id"]: p for p in derived_doc["papers"]}
        for p in sources["papers"]:
            built = derived.get(p["id"], {})
            if built.get("verdict_summary"):
                p["verdict_summary"] = built["verdict_summary"]
            # The derived score, so the page shows what the dashboard shows (same_as resolved).
            p["replica"] = built.get("replica")
        audit = derived_doc.get("audit")
    text = render(sources, audit)
    if args.write:
        OUT.write_bytes(text.encode("utf-8"))
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    if args.check:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else None
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run --write", file=sys.stderr)
            return 1
        print("replications page current")
        return 0
    parser.error("pass --write or --check")


if __name__ == "__main__":
    raise SystemExit(main())
