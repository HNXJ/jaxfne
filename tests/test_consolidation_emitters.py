def _fixture(with_schedule: bool):
    params, edges = build_ring_params_edges(N_NEURONS, delay_steps=DELAY_STEPS)
    params = dataclasses.replace(
        params, drive=jnp.full((N_NEURONS,), BASE_DRIVE, dtype=jnp.float32)
    )
    drive = None
    if with_schedule:
        drive = np.zeros((N_STEPS, N_NEURONS), dtype=np.float32)
        drive[:, 0] = DRIVE_LEVEL
        drive[:, 1] = DRIVE_LEVEL / 2.0
    return params, edges, drive


def _run(record: bool, with_schedule: bool) -> dict[str, np.ndarray]:
    params, edges, drive = _fixture(with_schedule)
    traces = (
        {"record_edge_current": True, "record_current_trace": True, "record_u_trace": True}
        if record
        else {}
    )
    voltages, spikes, sources, state = _simulate_edge_recurrent_izhikevich_delayed(
        params,
        edges,
        N_STEPS,
        DT_MS,
        jax.random.PRNGKey(SEED),
        drive_schedule=drive,
        **traces,
    )
    out = {
        "voltages": voltages,
        "spikes": spikes,
        "sources": sources,
        "presyn_trace": state["presynaptic_drive_trace"],
        "v": state["v"],
        "u": state["u"],
        "syn_state": state["syn_state"],
        "delay_state": state["delay_state"],
    }
    if record:
        out["edge_current_trace"] = state["edge_current_trace"]
        out["current_trace"] = state["current_trace"]
        out["u_trace"] = state["u_trace"]
    return {key: np.asarray(value) for key, value in out.items()}


@pytest.mark.parametrize(("name", "record", "with_schedule"), PATHS)
def test_scan_path_reproduces_pinned_outputs(name, record, with_schedule):
    out = _run(record, with_schedule)
    pinned = PINNED[name]
    assert set(out) == set(pinned), "scan output keys changed"
    assert float(out["spikes"].sum()) > 0, "fixture must spike on this path"
    for key, expected in pinned.items():
        actual = out[key]
        assert actual.shape == SHAPES[key], key
        assert actual.dtype == np.float32, key
        if key == "spikes":
            np.testing.assert_array_equal(actual, expected, err_msg=key)
        else:
            np.testing.assert_allclose(actual, expected, rtol=0, atol=0, err_msg=key)
